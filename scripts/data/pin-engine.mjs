import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {DEFAULT_PARAMETERS} from '../../lib/geometry/index.mjs';
const sha=data=>createHash('sha256').update(data).digest('hex');
const source=await fs.readFile(new URL('../../lib/geometry/index.mjs',import.meta.url));
const text=`// Generated by scripts/data/pin-engine.mjs. Do not edit by hand.\nexport const ENGINE_SOURCE_SHA256 = '${sha(source)}';\nexport const PARAMETERS_SHA256 = '${sha(JSON.stringify(DEFAULT_PARAMETERS))}';\n`;
await fs.writeFile(new URL('../../lib/geometry/identity.mjs',import.meta.url),text);
console.log('Pinned geometry implementation and default parameters.');
